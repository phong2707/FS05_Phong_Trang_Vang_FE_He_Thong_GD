export const subjectTestsService = {
  async getTeacherSubjectTests(subjectId: string): Promise<TestItem[]> {
    return withMockFallback(
      async () => {
        const response = await apiClient.get(`/v1/teacher/subjects/${subjectId}/tests`);
        return response?.data?.data || [];
      },
      () => mockTests
    );
  },

  async getSubjectChapters(subjectId: string): Promise<ChapterItem[]> {
    return withMockFallback(
      async () => {
        const response = await apiClient.get(`/v1/subjects/${subjectId}/chapters`);
        return response?.data?.data || [];
      },
      () => [
        { id: 'ch-1', title: 'Chương 1: Tổng quan' },
        { id: 'ch-2', title: 'Chương 2: React cơ bản' },
      ]
    );
  },

  async getSubjectQuestions(subjectId: string): Promise<QuestionBankItem[]> {
    return withMockFallback(
      async () => {
        const response = await apiClient.get(`/v1/subjects/${subjectId}/questions`);
        return response?.data?.data || [];
      },
      () => [
        { id: 'q-1', content: 'React là gì?', questionFormat: 'SINGLE_CHOICE' },
        { id: 'q-2', content: 'Hook useEffect dùng để làm gì?', questionFormat: 'SINGLE_CHOICE' },
        { id: 'q-3', content: 'So sánh state và props', questionFormat: 'ESSAY' },
      ]
    );
  },

  async createChapterTest(chapterId: string, payload: CreateTestPayload) {
    return apiClient.post(`/v1/chapters/${chapterId}/tests`, payload);
  },

  async createSubjectTest(subjectId: string, payload: CreateTestPayload) {
    return apiClient.post(`/v1/subjects/${subjectId}/tests`, payload);
  },

  async updateTest(testId: string, payload: UpdateTestPayload) {
    return apiClient.put(`/v1/tests/${testId}`, payload);
  },

  async deleteTest(testId: string) {
    return apiClient.delete(`/v1/tests/${testId}`);
  },

  async getTestSubmissions(testId: string): Promise<SubmissionItem[]> {
    return withMockFallback(
      async () => {
        const response = await apiClient.get(`/v1/tests/${testId}/submissions`);
        return response?.data?.data || [];
      },
      () => mockSubmissions
    );
  },

  async gradeAssignmentSubmission(
    submissionId: string,
    payload: { score: number; teacherFeedback?: string; feedbackFileUrl?: string }
  ): Promise<SubmissionItem> {
    return withMockFallback(
      async () => {
        const response = await apiClient.post(`/v1/assignments/${submissionId}/grade`, payload);
        return response?.data?.data;
      },
      () => ({
        ...mockSubmissions[0],
        id: submissionId,
        status: 'GRADED',
        score: payload.score,
        finalScoreStatus: 'MANUAL_GRADED',
      })
    );
  },
};
