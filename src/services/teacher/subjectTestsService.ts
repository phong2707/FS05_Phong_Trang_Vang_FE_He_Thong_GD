import apiClient from '@/api/apiClient';

export interface TestItem {
  id: string;
  title: string;
  testType: 'QUIZ' | 'ESSAY';
  scope: 'CHAPTER' | 'SUBJECT' | 'COURSE';
  isAutoGenerated: boolean;
  durationMinutes: number;
  startTime: string | null;
  endTime: string | null;
  maxAttempts: number;
  createdAt: string;
  submissionCount: number;
  questionCount: number;
  chapterId: string | null;
  chapterTitle: string | null;
}

export interface SubmissionItem {
  id: string;
  status: 'PENDING' | 'GRADED';
  score: number | null;
  submittedAt: string;
  finalScoreStatus: string | null;
  student: {
    id: string;
    firstName: string;
    lastName: string;
    middleName: string | null;
    email: string;
    avatarUrl: string | null;
  };
  userAnswers?: { essayAnswer: string | null }[];
}

export interface GenerationRule {
  questionFormat: string;
  totalCount: number;
  pointsPerQuestion: number;
}

export interface CreateTestPayload {
  title: string;
  testType: 'QUIZ' | 'ESSAY';
  durationMinutes: number;
  startTime?: string | null;
  endTime?: string | null;
  maxAttempts: number;
  isAutoGenerated: boolean;
  questionIds: string[];
  generationRules?: GenerationRule[];
}

export interface UpdateTestPayload {
  title?: string;
  durationMinutes?: number;
  startTime?: string | null;
  endTime?: string | null;
  maxAttempts?: number;
}

export interface ChapterItem {
  id: string;
  title: string;
}

export interface QuestionBankItem {
  id: string;
  content: string;
  questionFormat: string;
  typeId?: string;
}

const withMockFallback = async <T,>(
  apiCall: () => Promise<T>,
  fallback: () => T
): Promise<T> => {
  try {
    return await apiCall();
  } catch {
    return fallback();
  }
};

