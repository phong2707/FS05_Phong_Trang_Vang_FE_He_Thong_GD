export const subjectTestsService = {
  async getTeacherSubjectTests(subjectId: string): Promise<TestItem[]> {
    return callApi(
      async () => {
        // ✅ 1. lấy test theo SUBJECT
        const subjectRes = await apiClient.get<ApiResponse<TestItem[]>>(
          `/v1/subjects/${subjectId}/tests`,
        );

        const subjectTests = subjectRes.data.data || [];

        console.log("SUBJECT TESTS:", subjectTests);

        // ✅ 2. lấy danh sách chapter
        const chapterRes = await apiClient.get(`/v1/subjects/${subjectId}`);

        const chapters =
          chapterRes.data?.data?.chapters || chapterRes.data?.chapters || [];

        console.log("CHAPTER LIST:", chapters);
        // ✅ 3. lấy test của từng chapter

        const chapterTestsArr = await Promise.all(
          chapters.map((c: ChapterApi) =>
            apiClient
              .get(`/v1/chapters/${c.id}/tests`)
              .then((res) => {
                const list = res?.data?.data || [];
                console.log("CHAPTER ID:", c.id, "LIST:", list);

                return list.map((t: TestItem) => ({
                  ...t,
                  chapterId: c.id,
                  chapterTitle: c.title || c.name || "",
                }));
              })
              .catch((err) => {
                console.error("CHAPTER ERROR:", err);
                return [];
              }),
          ),
        );

        const chapterTests = chapterTestsArr.flat();
        console.log("CHAPTER TESTS:", chapterTests);

        const chapterMap = new Map<string, ChapterApi>();

        chapterTests.forEach((t) => {
          if (t.chapterId) {
            chapterMap.set(t.chapterId, {
              id: t.chapterId,
              title: t.chapterTitle || "Chương",
            });
          }
        });

        const chaptersFromTests = Array.from(chapterMap.values());
        console.log("CHAPTER FROM TEST:", chaptersFromTests);

        // ✅ 4. merge + tránh trùng id
        const map = new Map<string, TestItem>();

        [...subjectTests, ...chapterTests].forEach((t) => {
          const key = `${t.id}-${t.chapterId || "subject"}`;
          map.set(key, t);
        });

        return Array.from(map.values());
      },
      () => mockTests,
    );
  },

  async getChapterTests(chapterId: string): Promise<TestItem[]> {
    const response = await apiClient.get(`/v1/chapters/${chapterId}/tests`);

    return response?.data?.data || [];
  },

  async getSubjectChapters(subjectId: string): Promise<ChapterItem[]> {
    return callApi(async () => {
      const response = await apiClient.get(
        `/v1/subjects/${subjectId}/chapters`,
      );

      const data = response?.data?.data || [];

      return data.map((c: ChapterApi) => ({
        id: c.id,
        title: c.title || c.name || "",
      }));
    });
  },

  async getSubjectQuestions(
    subjectId: string,
    chapterId?: string,
  ): Promise<QuestionBankItem[]> {
    return callApi(async () => {
      const response = await apiClient.get(`/v1/questions`, {
        params: {
          subjectId,
          chapterId: chapterId || undefined,
          page: 1,
          pageSize: 100, // ✅ lấy hết câu hỏi
        },
      });

      console.log("RAW FIXED API:", response.data);

      const items: QuestionApi[] = response?.data?.data?.items || [];

      return items.map((q) => ({
        id: q.id,
        content: q.content,
        questionFormat: q.questionFormat,
        chapterId: q.chapterId,
      }));
    });
  },

  async createChapterTest(chapterId: string, payload: CreateTestPayload) {
    return apiClient.post(`/v1/chapters/${chapterId}/tests`, payload);
  },

  async createSubjectTest(subjectId: string, payload: CreateTestPayload) {
    return apiClient.post(`/v1/subjects/${subjectId}/tests`, payload);
  },

  async createCourseTest(courseId: string, payload: CreateTestPayload) {
    return apiClient.post(`/v1/courses/${courseId}/tests`, payload);
  },
  async generateTest(payload: {
    scope: "CHAPTER" | "SUBJECT" | "COURSE";
    chapterId?: string;
    subjectId?: string;
    courseId?: string;
    rule: {
      easy?: number;
      medium?: number;
      hard?: number;
    };
  }) {
    return apiClient.post(`/v1/tests/generate`, payload);
  },

  async updateTest(testId: string, payload: UpdateTestPayload) {
    return apiClient.put(`/v1/tests/${testId}`, payload);
  },

  async deleteTest(testId: string) {
    return apiClient.delete(`/v1/tests/${testId}`);
  },

  async getTestSubmissions(testId: string): Promise<SubmissionItem[]> {
    return callApi(async () => {
      const response = await apiClient.get(`v1/tests/${testId}/submissions`);
      return response?.data?.data || [];
    });
  },

  async gradeAssignmentSubmission(
    submissionId: string,
    payload: {
      score?: number;
      feedback?: string;
      feedbackFileUrl?: string;
      useAI?: boolean;
    },
  ): Promise<SubmissionItem> {
    return callApi(
      async () => {
        const response = await apiClient.post(
          `/v1/assignments/${submissionId}/grade`,
          payload,
        );
        return response?.data?.data;
      },
      () => ({
        ...mockSubmissions[0],
        id: submissionId,
        status: "GRADED",
        score: payload.score,
        finalScoreStatus: "MANUAL_GRADED",
      }),
    );
  },

  async previewAIGrade(submissionId: string) {
    const response = await apiClient.post(
      `/v1/assignments/${submissionId}/grade`,
      {
        useAI: true,
        preview: true,
      },
    );
    return response?.data?.data;
  },
};
