const callApi = async <T>(
  apiCall: () => Promise<T>,
  fallback?: () => T,
): Promise<T> => {
  try {
    return await apiCall();
  } catch (err) {
    console.error("API ERROR:", err);
    if (fallback) return fallback();
    throw err;
  }
};

